// Generates host/stubs/waylithaudio.c from the P/Invoke declarations in the decompiled engine (ref/Waylith.decompiled.cs):
// every wa_* function with the right signature, returning 0 / NULL, except that creation functions hand out
// non-zero fake handles (the engine treats 0 as failure). usage: node host/stubs/gen-audio-stub.js
const fs = require('fs');
// Function pointer parameters (delegate* unmanaged[Cdecl]<...>) carry commas and brackets of their own: flattened first.
const src = fs.readFileSync('ref/Waylith.decompiled.cs', 'utf8').replace(/delegate\*\s*unmanaged(\[[^\]]*\])?<[^<>]*>/g, 'void*');
const decls = new Map();
const re = /extern\s+([A-Za-z0-9_<>\[\]\*\.`,\s]+?)\s+(wa_[a-z0-9_]+)\s*\(([^)]*)\)\s*;/g;
let m;
while ((m = re.exec(src)) !== null) {
	const [, ret, name, args] = m;
	if (name.startsWith('__')) continue;
	decls.set(name, { ret: ret.trim().replace(/^unsafe\s+/, ''), args: args.trim() });
}
// LibraryImport methods are declared with an EntryPoint and a local __PInvoke; the generated stub's signature follows
// the attribute within a few hundred characters.
const re2 = /EntryPoint = "(wa_[a-z0-9_]+)"[^]{0,600}?extern\s+(?:unsafe\s+)?([A-Za-z0-9_\*]+)\s+__PInvoke\(([^)]*)\)/g;
while ((m = re2.exec(src)) !== null) {
	const [, name, ret, args] = m;
	if (!decls.has(name)) decls.set(name, { ret: ret.trim(), args: args.replace(/__(\w+)_native/g, '$1').trim() });
}
// Whatever the patterns miss, by the names the native library exports (from its export table), with a plain signature.
for (const name of ['wa_probe_file', 'wa_probe_memory', 'wa_sound_load_file_stream']) {
	if (!decls.has(name)) {
		decls.set(name, name === 'wa_probe_file' ? { ret: 'int', args: 'byte* path, ulong* frames, uint* channels, uint* rate' }
			: name === 'wa_probe_memory' ? { ret: 'int', args: 'void* data, nuint length, ulong* frames, uint* channels, uint* rate' }
			: { ret: 'ulong', args: 'byte* path' });
	}
}
function cType(t) {
	t = t.replace(/\bin\s+|\bout\s+|\bref\s+/g, '').trim();
	const map = { 'uint': 'uint32_t', 'ulong': 'uint64_t', 'int': 'int', 'long': 'int64_t', 'float': 'float', 'double': 'double', 'nuint': 'size_t', 'nint': 'intptr_t', 'void': 'void', 'byte': 'uint8_t', 'sbyte': 'int8_t', 'short': 'int16_t', 'ushort': 'uint16_t', 'bool': 'int', 'string': 'const char*' };
	let stars = '';
	while (t.endsWith('*')) { stars += '*'; t = t.slice(0, -1).trim(); }
	if (t.startsWith('delegate')) return 'void*';
	if (t.includes('IntPtr') || t.includes('Span') || t.includes('[]')) return 'void*';
	return (map[t] || 'void*') + stars;
}
const lines = [
	'// Generated by gen-audio-stub.js from the engine\'s P/Invoke declarations: a silent stand-in for waylithaudio',
	'// (the engine\'s miniaudio wrapper) until the port has audio. Creation functions return non-zero fake handles',
	'// because the engine treats 0 as "could not create"; everything else returns 0 or NULL.',
	'#include <stdint.h>',
	'#include <stddef.h>',
	'#define EXPORT __attribute__((visibility("default")))',
	'static uint64_t next_handle = 1;',
	'static uint64_t handle(void) { return __atomic_fetch_add(&next_handle, 1, __ATOMIC_RELAXED); }',
	'',
];
for (const [name, d] of [...decls.entries()].sort()) {
	const ret = cType(d.ret);
	const params = d.args ? d.args.split(',').map((a, i) => {
		const parts = a.trim().split(/\s+/);
		const pname = parts.pop();
		return cType(parts.join(' ')) + ' ' + (pname || ('a' + i));
	}) : [];
	const names = params.map(p => p.split(' ').pop());
	let body;
	const creates = /_create|_load_|_play$|_tap_create/.test(name);
	if (ret === 'void') body = '';
	else if (ret.endsWith('*')) body = 'return NULL;';
	else if (ret === 'uint64_t' && creates) body = 'return handle();';
	else if (name === 'wa_sample_rate') body = 'return 48000;';
	else if (name === 'wa_channels' || name === 'wa_sound_channels' || name === 'wa_tap_channels') body = 'return 2;';
	else body = 'return 0;';
	const unused = names.map(n => `(void)${n};`).join(' ');
	lines.push(`EXPORT ${ret} ${name}(${params.join(', ') || 'void'}) { ${unused} ${body} }`);
}
fs.writeFileSync('host/stubs/waylithaudio.c', lines.join('\n') + '\n');
console.log(`${decls.size} functions`);
